"""Scheduled runs: job definitions, wrapper scripts and OS scheduler commands.

Every job runs Claude Code headless with ADS_GODMODE_UNATTENDED=1. In that
mode the write gate denies anything that would need a human yes, and denies
all writes for clients unless their autopilot is on (or they set
automation.allow_unattended_writes). So scheduled runs are read-only except
autopilot actions inside each opted-in client's limits.

Each job is a small wrapper script in ADS_GODMODE_HOME/jobs/ (Windows .cmd or
POSIX .sh). The OS scheduler only calls the script, which keeps the scheduler
entry short (schtasks /TR is limited to 261 characters) and quoting simple.
"""

import os
import shlex
import shutil
import stat
from typing import Dict, List

from . import paths

JOBS: List[Dict] = [
    {"name": "daily-check", "cron": "30 7 * * *", "windows": ("DAILY", "07:30"),
     "prompt": "/ads:sweep daily",
     "what": "Every morning: refresh yesterday/today spend for every client, flag runaway spend and "
             "broken tracking, write the portfolio dashboard. Read-only."},
    {"name": "weekly-review", "cron": "0 7 * * 1", "windows": ("WEEKLY /D MON", "07:00"),
     "prompt": "/ads:sweep weekly",
     "what": "Mondays: full 7-day vs prior-week snapshots, judge changes whose read date passed "
             "(learning loop), per-client reports with what worked / what didn't and recommended fixes."},
    {"name": "autopilot-run", "cron": "0 9 * * *", "windows": ("DAILY", "09:00"),
     "prompt": "/ads:autopilot all run",
     "what": "Every morning, only for clients with autopilot ON: pause clear losers, swap tired ads in the "
             "same ad set within the daily spend cap, add small Google negative lists. Everything else waits "
             "for approval in the report.", "optional": True},
    {"name": "monthly-report", "cron": "0 8 1 * *", "windows": ("MONTHLY /D 1", "08:00"),
     "prompt": "/ads:sweep monthly",
     "what": "1st of the month: owner-friendly monthly report per client plus a portfolio summary."},
]

# Read tools for the configured ad/analytics servers, python for adsgm, file writes for reports.
# The write gate still denies every ad-platform write that is not allowed unattended.
ALLOWED_TOOLS = ["mcp__plugin_ads_meta-ads", "mcp__meta-ads", "mcp__google-ads", "mcp__google-analytics",
                 "Bash(python:*)", "Bash(python3:*)", "Read", "Write", "Glob", "Grep", "Skill"]


def jobs_dir():
    return paths.home() / "jobs"


def logs_dir():
    return paths.home() / "logs"


def headless_args(prompt: str, claude: str = "claude") -> List[str]:
    return [claude, "-p", prompt, "--allowedTools", *ALLOWED_TOOLS]


def _claude_path() -> str:
    return shutil.which("claude") or "claude"


def script_path(job: Dict, os_name: str):
    return jobs_dir() / (f"{job['name']}.cmd" if os_name == "windows" else f"{job['name']}.sh")


def script_text(job: Dict, os_name: str, claude: str) -> str:
    log = logs_dir() / f"{job['name']}.log"
    if os_name == "windows":
        args = " ".join(f'"{a}"' if any(ch in a for ch in ' *()/:') else a for a in headless_args(job["prompt"], claude))
        return ("@echo off\r\n"
                "rem Ads God Mode scheduled job - generated by `adsgm schedule plan --write`\r\n"
                "set ADS_GODMODE_UNATTENDED=1\r\n"
                f'if not exist "{logs_dir()}" mkdir "{logs_dir()}"\r\n'
                f'cd /d "{paths.home()}"\r\n'
                f'{args} >> "{log}" 2>&1\r\n')
    args = " ".join(shlex.quote(a) for a in headless_args(job["prompt"], claude))
    return ("#!/bin/sh\n"
            "# Ads God Mode scheduled job - generated by `adsgm schedule plan --write`\n"
            "export ADS_GODMODE_UNATTENDED=1\n"
            f"mkdir -p {shlex.quote(str(logs_dir()))}\n"
            f"cd {shlex.quote(str(paths.home()))}\n"
            f"{args} >> {shlex.quote(str(log))} 2>&1\n")


def write_scripts(os_name: str) -> List[str]:
    jobs_dir().mkdir(parents=True, exist_ok=True)
    claude = _claude_path()
    out = []
    for j in JOBS:
        p = script_path(j, os_name)
        p.write_text(script_text(j, os_name, claude), encoding="utf-8", newline="")
        if os_name != "windows":
            p.chmod(p.stat().st_mode | stat.S_IXUSR)
        out.append(str(p))
    return out


def posix_line(job: Dict) -> str:
    return f"{job['cron']} {shlex.quote(str(script_path(job, 'posix')))}"


def windows_command(job: Dict) -> str:
    sched, start = job["windows"]
    return (f'schtasks /Create /TN "AdsGodMode-{job["name"]}" /SC {sched} /ST {start} '
            f'/TR "\\"{script_path(job, "windows")}\\"" /F')


def plan(os_name: str = "posix", write: bool = False) -> Dict:
    written = write_scripts(os_name) if write else []
    jobs = []
    for j in JOBS:
        jobs.append({"name": j["name"], "what": j["what"], "prompt": j["prompt"], "optional": j.get("optional", False),
                     "env": {"ADS_GODMODE_UNATTENDED": "1"}, "allowed_tools": ALLOWED_TOOLS,
                     "script": str(script_path(j, os_name)),
                     "command": windows_command(j) if os_name == "windows" else posix_line(j)})
    return {"jobs": jobs, "scripts_written": written,
            "notes": ["Run with --write first so the wrapper scripts exist, then install the commands (or use the "
                      "host app's scheduler with each job's prompt and ADS_GODMODE_UNATTENDED=1).",
                      "Runs are read-only except autopilot actions for clients that switched autopilot on.",
                      "Remove: schtasks /Delete /TN AdsGodMode-<name> /F, or delete the crontab line; "
                      "the scripts live in " + str(jobs_dir()) + "."]}
